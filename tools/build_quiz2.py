def balance_answers():
    """Rotate concept options so the correct choice is not always first."""
    concept = [q for q in Q if q["type"] == "concept"]
    calc_counts = {i: 0 for i in range(4)}
    for q in Q:
        if q["type"] == "calc":
            calc_counts[q["answer"]] += 1

    target = [0] * 13 + [1] * 13 + [2] * 12 + [3] * 12
    for i in range(4):
        for _ in range(calc_counts[i]):
            target.remove(i)
    random.Random(20261102).shuffle(target)

    for q, pos in zip(concept, target):
        shift = (q["answer"] - pos) % 4
        if shift:
            q["options"] = q["options"][shift:] + q["options"][:shift]
            q["answer"] = pos


def main():
    assert len(Q) == 50, len(Q)
    balance_answers()

    ids = [q["id"] for q in Q]
    assert ids == list(range(1, 51))
    for q in Q:
        assert len(q["options"]) == 4, q["id"]
        assert len(set(q["options"])) == 4, q["id"]
        assert 0 <= q["answer"] < 4, q["id"]
        assert q["ch"] in {"00", "01", "02", "03"}, q["id"]
        assert q["type"] in {"concept", "calc"}, q["id"]

    data = {"meta": META, "questions": Q}
    out = ROOT / "data" / "quiz2.json"
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    dist = {k: sum(1 for q in Q if q["answer"] == k) for k in range(4)}
    chapters = {c: sum(1 for q in Q if q["ch"] == c) for c in ("00", "01", "02", "03")}
    kinds = {k: sum(1 for q in Q if q["type"] == k) for k in ("concept", "calc")}
    print(f"wrote {out} | {len(Q)} questions | chapters={chapters} | types={kinds} | answers={dist}")


if __name__ == "__main__":
    main()
